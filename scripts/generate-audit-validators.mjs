import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { auditRuntimeContracts } from "./contract-artifacts.mjs";
import { frontendRoot, openApiPath } from "./contract-provenance.mjs";

const temporaryDirectory = mkdtempSync(join(tmpdir(), "audit-validators-"));
const generatedClientPath = join(temporaryDirectory, "openapi-client.ts");

try {
  execFileSync(
    process.execPath,
    [
      "x",
      "openapi-zod-client",
      openApiPath,
      "--strict-objects",
      "--export-schemas",
      "--output",
      generatedClientPath,
    ],
    { cwd: frontendRoot, stdio: "inherit" },
  );

  const generatedClient = readFileSync(generatedClientPath, "utf8");

  for (const contract of auditRuntimeContracts) {
    const { eventOptions, envelopeFields } = extractPageSchema(
      generatedClient,
      contract.schemaName,
    );
    writeFileSync(
      contract.outputPath,
      renderRuntimeContract(contract, eventOptions, envelopeFields),
      "utf8",
    );
  }

  execFileSync(
    process.execPath,
    [
      "x",
      "biome",
      "format",
      "--write",
      ...auditRuntimeContracts.map(({ outputPath }) => outputPath),
    ],
    { cwd: frontendRoot, stdio: "inherit" },
  );
} finally {
  rmSync(temporaryDirectory, { recursive: true, force: true });
}

function extractPageSchema(source, schemaName) {
  const declarationStart = source.indexOf(`const ${schemaName} = z`);
  if (declarationStart === -1) {
    throw new Error(`Could not find generated schema ${schemaName}`);
  }

  const declarationEnd = source.indexOf(";\n", declarationStart);
  if (declarationEnd === -1) {
    throw new Error(`Could not find the end of generated schema ${schemaName}`);
  }

  const declaration = source.slice(declarationStart, declarationEnd + 1);
  const pattern = new RegExp(
    `^const ${schemaName} = z\\n  \\.object\\(\\{\\n    items: z\\.array\\(\\n      z\\.union\\(\\[\\n([\\s\\S]*?)      \\]\\)\\n    \\),\\n([\\s\\S]*?)  \\}\\)\\n  \\.strict\\(\\);$`,
  );
  const match = declaration.match(pattern);
  if (!match?.[1] || !match[2]) {
    throw new Error(`Generated schema ${schemaName} did not match the expected cursor-page shape`);
  }

  return { eventOptions: match[1], envelopeFields: match[2] };
}

function renderRuntimeContract(contract, eventOptions, envelopeFields) {
  const {
    schemaName,
    eventName,
    itemName,
    unrecognizedName,
    envelopeName,
    parserName,
    itemParserName,
    rationale,
  } = contract;

  return `// Generated by scripts/generate-audit-validators.mjs from contracts/openapi.json.
// Do not edit this file directly.

import { z } from "zod";

${rationale ? `// ${rationale}\n` : ""}// A plain union rather than one discriminated on \`eventType\`: the catalog versions an
// event's payload without renaming the event, so two arms can carry the same event type.
export const ${eventName} = z.union([
${eventOptions}]);

export const ${envelopeName} = z
  .object({
    items: z.array(z.unknown()),
${envelopeFields}  })
  .strict();

export type ${eventName} = z.infer<typeof ${eventName}>;

export interface ${unrecognizedName} {
  eventType: "__unrecognized__";
  raw: unknown;
}

export type ${itemName} = ${eventName} | ${unrecognizedName};

export interface ${schemaName}
  extends Omit<z.infer<typeof ${envelopeName}>, "items"> {
  items: ${itemName}[];
}

export function ${parserName}(value: unknown): ${schemaName} {
  const envelope = ${envelopeName}.parse(value);

  return {
    ...envelope,
    items: envelope.items.map(${itemParserName}),
  };
}

function ${itemParserName}(raw: unknown): ${itemName} {
  const result = ${eventName}.safeParse(raw);
  if (result.success) return result.data;

  return { eventType: "__unrecognized__", raw };
}
`;
}
