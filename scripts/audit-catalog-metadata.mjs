// The event-metadata table the Admin Portal reads, collected from the vendored contract.
// The backend annotates each response arm with what its catalog definition knows; this
// reads those annotations back out, so the table cannot drift from the catalog.

import { readFileSync } from "node:fs";
import { openApiPath } from "./contract-provenance.mjs";

/** The projection's own placeholder — it stands for a row nobody recorded, so the catalog omits it. */
const UNAVAILABLE_EVENT_TYPE = "audit.event.unavailable";

function armsOf(document, schemaName) {
  const page = document.components?.schemas?.[schemaName];
  if (!page) throw new Error(`Contract is missing ${schemaName}`);
  return page.properties.items.items.anyOf.filter(
    (arm) => arm.properties.eventType.enum[0] !== UNAVAILABLE_EVENT_TYPE,
  );
}

function annotation(arm, key, eventType) {
  const value = arm[key];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`Contract arm ${eventType} is missing the ${key} annotation`);
  }
  return value;
}

/**
 * Every catalog event, keyed by event type. Audience is not annotated: an event is readable
 * by a Company exactly when the Company page schema carries an arm for it, which is the same
 * fact the backend derives its two unions from.
 */
export function collectAuditCatalogMetadata() {
  const document = JSON.parse(readFileSync(openApiPath, "utf-8"));
  const companyEventTypes = new Set(
    armsOf(document, "CompanyAuditTrailPage").map((arm) => arm.properties.eventType.enum[0]),
  );

  return armsOf(document, "PlatformAuditTrailPage")
    .map((arm) => {
      const eventType = arm.properties.eventType.enum[0];
      return {
        eventType,
        description: annotation(arm, "description", eventType),
        lifecycle: annotation(arm, "x-audit-lifecycle", eventType),
        outcomePolicy: annotation(arm, "x-audit-outcome-policy", eventType),
        personalData: annotation(arm, "x-audit-personal-data", eventType),
        scope: arm.properties.scope.enum[0],
        audience: companyEventTypes.has(eventType) ? "COMPANY" : "PLATFORM",
      };
    })
    .sort((left, right) => left.eventType.localeCompare(right.eventType));
}

/**
 * The generated module's source. Biome formats it after the write, as every generator here
 * does, so this renders each entry as one literal rather than guessing at line breaks.
 */
export function renderAuditCatalogMetadata(events) {
  const entries = events.map((event) => `  ${JSON.stringify(event)},`).join("\n");

  return `// Generated by scripts/generate-audit-catalog.mjs from contracts/openapi.json.
// Do not edit this file directly.

/** What the Audit Event Catalog knows about one event type, beyond the rows it produces. */
export interface AuditEventMetadata {
  eventType: string;
  /** The catalog's own sentence about the event, shown beside the row that prompted the question. */
  description: string;
  lifecycle: "ACTIVE" | "DEPRECATED";
  /** Why an event may never appear as a failure: SUCCESS_ONLY events cannot record one. */
  outcomePolicy: "SUCCESS_ONLY" | "ALLOW_FAILURE";
  /** Whether the event carries personal data an erasure request must reach. */
  personalData: "none" | "erase";
  scope: "PLATFORM" | "COMPANY";
  /** Who may read it — a COMPANY event reaches the tenant's own trail as well. */
  audience: "PLATFORM" | "COMPANY";
}

export const auditEventCatalog: readonly AuditEventMetadata[] = [
${entries}
];

const byEventType = new Map(auditEventCatalog.map((event) => [event.eventType, event]));

/** The catalog entry for an event type, or \`undefined\` for a row this build has never heard of. */
export function auditEventMetadata(eventType: string): AuditEventMetadata | undefined {
  return byEventType.get(eventType);
}
`;
}
