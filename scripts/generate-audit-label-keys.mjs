// Emits the two artifacts derived from the Audit Trail label key set: the manifest
// `check-audit-labels.mjs` measures the authored resources against, and the list of
// closed-enum fields the detail renderer formats values for.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { collectAuditLabelKeys } from "./audit-label-keys.mjs";
import { auditLabelArtifacts } from "./contract-artifacts.mjs";
import { frontendRoot } from "./contract-provenance.mjs";

const { manifestPath, enumFieldsPath } = auditLabelArtifacts;
const { events, fields, enums } = collectAuditLabelKeys();

writeFileSync(manifestPath, `${JSON.stringify({ events, fields, enums }, null, 2)}\n`, "utf-8");
writeFileSync(enumFieldsPath, renderEnumFields(Object.keys(enums)), "utf-8");

execFileSync(process.execPath, ["x", "biome", "format", "--write", enumFieldsPath], {
  cwd: frontendRoot,
  stdio: "inherit",
});

function renderEnumFields(fieldNames) {
  return `// Generated by scripts/generate-audit-label-keys.mjs from contracts/openapi.json.
// Do not edit this file directly.

/**
 * The audit detail fields the contract closes to a fixed set of values. A field listed
 * here renders through the enum formatter, so a value the contract adds later reads as
 * words rather than as a raw token.
 */
export const auditEnumFields: readonly string[] = [
${fieldNames.map((field) => `  ${JSON.stringify(field)},`).join("\n")}
];
`;
}
