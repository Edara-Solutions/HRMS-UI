import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { isDelegatedOperation } from "./contract-audiences.mjs";
import {
  audienceOpenApiPaths,
  contractsDir,
  frontendRoot,
  openApiPath,
  readProvenance,
} from "./contract-provenance.mjs";

const generatedRoot = join(frontendRoot, "src", "shared", "api", "generated");
const methods = new Set(["delete", "get", "head", "options", "patch", "post", "put", "trace"]);
const documents = {
  company: audienceOpenApiPaths.company,
  delegated: audienceOpenApiPaths.delegated,
  platform: audienceOpenApiPaths.platform,
  public: audienceOpenApiPaths.public,
};

const operationLedger = {};
for (const [audience, documentPath] of Object.entries(documents)) {
  const generationPath = audience === "delegated" ? audienceOpenApiPaths.platform : documentPath;
  const document = readDocument(generationPath);
  const outputDir = join(generatedRoot, audience);
  if (!outputDir.startsWith(generatedRoot)) throw new Error("Unsafe generated output path");
  rmSync(outputDir, { recursive: true, force: true });
  mkdirSync(outputDir, { recursive: true });
  const seen = new Set();
  const operations = [];
  for (const [path, pathItem] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem)) {
      if (!methods.has(method)) continue;
      const delegated = isDelegatedOperation(operation);
      if ((audience === "platform" && delegated) || (audience === "delegated" && !delegated))
        continue;
      const fileName = canonicalFileName(method, path);
      if (seen.has(fileName))
        throw new Error(`Generated filename collision: ${audience}/${fileName}`);
      seen.add(fileName);
      const requestSchema = renderRequest(pathItem.parameters ?? [], operation, document);
      const responses = renderResponses(operation.responses ?? {}, document);
      const key = `${method.toUpperCase()} ${path}`;
      writeFileSync(
        join(outputDir, fileName),
        renderModule({
          audience,
          key,
          method,
          path,
          requestSchema,
          responses,
          successStatuses: Object.keys(operation.responses ?? {}).filter((status) =>
            /^2\d\d$/.test(status),
          ),
        }),
      );
      operations.push({ file: fileName, key });
    }
  }
  operations.sort((left, right) => left.key.localeCompare(right.key));
  operationLedger[audience] = operations;
}

const provenance = readProvenance();
const contracts = Object.fromEntries(
  [["internal", openApiPath], ...Object.entries(documents)].map(([name, path]) => [
    name,
    { file: relative(frontendRoot, path).replaceAll("\\", "/"), sha256: hashFile(path) },
  ]),
);
writeFileSync(
  join(contractsDir, "provenance.json"),
  `${JSON.stringify({ ...provenance, generatorVersion: 1, contracts, operations: operationLedger }, null, 2)}\n`,
);
writeFileSync(
  join(generatedRoot, "metadata.ts"),
  `// Generated by scripts/generate-audience-contracts.mjs. Do not edit.\nexport const generatedContractProvenance = ${JSON.stringify(
    {
      backendCommit: provenance.commit,
      generatorVersion: 1,
      hashes: Object.fromEntries(
        Object.entries(contracts).map(([name, value]) => [name, value.sha256]),
      ),
    },
    null,
    2,
  )} as const;\n`,
);
execFileSync(process.execPath, ["x", "--no-install", "biome", "format", "--write", generatedRoot]);

function readDocument(path) {
  if (!existsSync(path)) throw new Error(`Missing audience contract: ${path}`);
  return JSON.parse(readFileSync(path, "utf8"));
}

function hashFile(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function canonicalFileName(method, path) {
  const normalized = path
    .replace(/^\/+/, "")
    .replace(/[{}]/g, "")
    .replace(/[^A-Za-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
  return `${method}-${normalized || "root"}.ts`;
}

function resolveSchema(schema, document, trail = new Set()) {
  if (!schema?.$ref) return schema ?? {};
  if (trail.has(schema.$ref)) throw new Error(`Recursive schema is unsupported: ${schema.$ref}`);
  const nextTrail = new Set(trail);
  nextTrail.add(schema.$ref);
  const target = schema.$ref
    .replace(/^#\//, "")
    .split("/")
    .reduce(
      (value, segment) => value?.[segment.replaceAll("~1", "/").replaceAll("~0", "~")],
      document,
    );
  if (!target) throw new Error(`Unknown schema reference ${schema.$ref}`);
  return {
    ...resolveSchema(target, document, nextTrail),
    ...Object.fromEntries(Object.entries(schema).filter(([key]) => key !== "$ref")),
  };
}

function renderSchema(rawSchema, document, trail = new Set()) {
  if (rawSchema?.$ref) {
    if (trail.has(rawSchema.$ref))
      throw new Error(`Recursive schema is unsupported: ${rawSchema.$ref}`);
    const nextTrail = new Set(trail);
    nextTrail.add(rawSchema.$ref);
    return renderSchema(resolveSchema(rawSchema, document, trail), document, nextTrail);
  }
  const schema = rawSchema ?? {};
  if (Array.isArray(schema.type)) {
    return `z.union([${schema.type
      .map((type) => renderSchema({ ...schema, type }, document, trail))
      .join(", ")}])`;
  }
  let rendered;
  if (schema.const !== undefined) rendered = `z.literal(${JSON.stringify(schema.const)})`;
  else if (schema.enum?.length)
    rendered =
      schema.enum.length === 1
        ? `z.literal(${JSON.stringify(schema.enum[0])})`
        : `z.union([${schema.enum.map((value) => `z.literal(${JSON.stringify(value)})`).join(", ")}])`;
  else if (schema.anyOf || schema.oneOf) {
    const variants = schema.anyOf ?? schema.oneOf;
    rendered =
      variants.length === 1
        ? renderSchema(variants[0], document, trail)
        : `z.union([${variants.map((value) => renderSchema(value, document, trail)).join(", ")}])`;
  } else if (schema.allOf?.length) {
    rendered = schema.allOf
      .map((value) => renderSchema(value, document, trail))
      .reduce((left, right) => `${left}.and(${right})`);
  } else if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? []);
    const properties = Object.entries(schema.properties ?? {}).map(
      ([name, value]) =>
        `${JSON.stringify(name)}: ${renderSchema(value, document, trail)}${required.has(name) ? "" : ".optional()"}`,
    );
    rendered = `z.object({ ${properties.join(", ")} })`;
    if (schema.additionalProperties === false) rendered += ".strict()";
    else if (typeof schema.additionalProperties === "object")
      rendered += `.catchall(${renderSchema(schema.additionalProperties, document, trail)})`;
  } else if (schema.type === "array")
    rendered = `z.array(${renderSchema(schema.items ?? {}, document, trail)})`;
  else if (schema.type === "integer") rendered = "z.number().int()";
  else if (schema.type === "number") rendered = "z.number()";
  else if (schema.type === "boolean") rendered = "z.boolean()";
  else if (schema.type === "null") rendered = "z.null()";
  else if (schema.type === "string") rendered = "z.string()";
  else rendered = "z.unknown()";
  if (schema.type === "string" && schema.minLength !== undefined)
    rendered += `.min(${schema.minLength})`;
  if (schema.type === "string" && schema.maxLength !== undefined)
    rendered += `.max(${schema.maxLength})`;
  if (schema.type === "string" && schema.pattern !== undefined) {
    const pattern = schema.pattern.replaceAll("/", "\\/").replaceAll("\n", "\\n");
    rendered += `.regex(/${pattern}/)`;
  }
  if ((schema.type === "integer" || schema.type === "number") && schema.minimum !== undefined)
    rendered += `.min(${schema.minimum})`;
  if ((schema.type === "integer" || schema.type === "number") && schema.maximum !== undefined)
    rendered += `.max(${schema.maximum})`;
  if (schema.type === "array" && schema.minItems !== undefined)
    rendered += `.min(${schema.minItems})`;
  if (schema.type === "array" && schema.maxItems !== undefined)
    rendered += `.max(${schema.maxItems})`;
  if (schema.type === "string" && schema.format === "uuid") rendered += ".uuid()";
  if (schema.type === "string" && schema.format === "email") rendered += ".email()";
  if (schema.type === "string" && schema.format === "date-time")
    rendered += ".datetime({ offset: true })";
  if (schema.type === "string" && schema.format === "uri") rendered += ".url()";
  if (schema.type === "string" && schema.format === "uri-reference")
    rendered +=
      '.refine((value) => { try { new URL(value, "https://contract.invalid"); return true; } catch { return false; } })';
  if (schema.nullable) rendered += ".nullable()";
  return rendered;
}

function renderRequest(pathParameters, operation, document) {
  const groups = { headers: [], params: [], query: [] };
  for (const parameter of [...pathParameters, ...(operation.parameters ?? [])]) {
    const group =
      parameter.in === "path" ? "params" : parameter.in === "header" ? "headers" : parameter.in;
    if (!groups[group]) continue;
    groups[group].push(
      `${JSON.stringify(parameter.name)}: ${renderSchema(parameter.schema, document)}${parameter.required ? "" : ".optional()"}`,
    );
  }
  const fields = Object.entries(groups)
    .filter(([, values]) => values.length)
    .map(([name, values]) => `${name}: z.object({ ${values.join(", ")} }).strict()`);
  const content = operation.requestBody?.content;
  const bodySchema =
    content?.["application/json"]?.schema ??
    (content ? Object.values(content)[0]?.schema : undefined);
  if (bodySchema)
    fields.push(
      `body: ${renderSchema(bodySchema, document)}${operation.requestBody.required ? "" : ".optional()"}`,
    );
  return `z.object({ ${fields.join(", ")} }).strict()`;
}

function renderResponses(responses, document) {
  return Object.entries(responses)
    .map(([status, response]) => {
      const content = response.content;
      const schema =
        content?.["application/json"]?.schema ??
        (content ? Object.values(content)[0]?.schema : undefined);
      return `${JSON.stringify(status)}: ${schema ? renderSchema(schema, document) : "null"}`;
    })
    .join(",\n    ");
}

function renderModule({ audience, key, method, path, requestSchema, responses, successStatuses }) {
  const successKeys =
    successStatuses.length > 0
      ? successStatuses.map((status) => JSON.stringify(status)).join(" | ")
      : "never";
  return `// Generated by scripts/generate-audience-contracts.mjs. Do not edit.\nimport { z } from "zod";\nimport { defineOperation } from "../runtime";\n\nexport const requestSchema = ${requestSchema};\nexport const responseSchemas = {\n    ${responses}\n} as const;\n\nexport const operation = defineOperation({\n  audience: ${JSON.stringify(audience)},\n  key: ${JSON.stringify(key)},\n  method: ${JSON.stringify(method.toUpperCase())},\n  path: ${JSON.stringify(path)},\n  requestSchema,\n  responses: responseSchemas,\n});\n\nexport type Request = z.infer<typeof requestSchema>;\nexport type SuccessSchema = (typeof responseSchemas)[${successKeys}];\nexport type SuccessResponse = SuccessSchema extends null ? undefined : z.infer<Exclude<SuccessSchema, null>>;\n`;
}
